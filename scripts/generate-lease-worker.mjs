#!/usr/bin/env node
// Pre-bundles the dedicated lease worker into a string constant so that
// `BrowserWorker` can start it from a Blob URL without a separate file and
// without consumer bundlers transforming its code.
//   node scripts/generate-lease-worker.mjs          write the file
//   node scripts/generate-lease-worker.mjs --check  exit 1 when stale
import { build } from "esbuild";
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const target = resolve(root, "src/browser/lease-worker-source.ts");

export async function renderLeaseWorkerModule() {
  const result = await build({
    entryPoints: [resolve(root, "scripts/lease-worker-entry.ts")],
    bundle: true,
    platform: "browser",
    format: "iife",
    target: "es2017",
    minify: true,
    legalComments: "none",
    write: false,
    logLevel: "silent",
  });
  const code = result.outputFiles[0].text.trim();
  return (
    "// GENERATED by scripts/generate-lease-worker.mjs from src/browser/engine.ts. Do not edit.\n" +
    "// Regenerate with `npm run generate:lease-worker`.\n" +
    `export const LEASE_WORKER_SOURCE = ${JSON.stringify(code)};\n`
  );
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const rendered = await renderLeaseWorkerModule();
  if (process.argv.includes("--check")) {
    let current = "";
    try { current = readFileSync(target, "utf8"); } catch {}
    if (current !== rendered) {
      console.error("src/browser/lease-worker-source.ts is stale; run `npm run generate:lease-worker`");
      process.exit(1);
    }
    console.log("✓ lease worker source is up to date");
  } else {
    writeFileSync(target, rendered);
    console.log(`wrote ${target} (${rendered.length} bytes)`);
  }
}
